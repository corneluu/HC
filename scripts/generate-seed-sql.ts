// Regenerates supabase/seed.sql from src/data/seed.ts: npm run seed:sql
import fs from "node:fs";
import { seed } from "../src/data/seed.ts";

const text = (v: string) => `'${v.replaceAll("'", "''")}'`;

class Json { value: unknown; constructor(value: unknown) { this.value = value; } }

function literal(v: unknown): string {
  if (v instanceof Json) return `${text(JSON.stringify(v.value))}::jsonb`;
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "string") return text(v);
  return `${text(JSON.stringify(v))}::jsonb`;
}

function insert(table: string, rows: Record<string, unknown>[], conflict: string) {
  if (!rows.length) return "";
  const columns = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${columns.map((c) => literal(r[c])).join(", ")})`).join(",\n");
  // do nothing: re-running must never overwrite edits made in the admin panel.
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict (${conflict}) do nothing;\n`;
}

const settings = Object.entries(seed.settings).map(([key, value]) => ({ key, value: new Json(value) }));

const sql = [
  "-- Generated by scripts/generate-seed-sql.ts. Safe to run more than once.",
  insert("events", seed.events, "id"),
  insert("council_members", seed.council, "id"),
  insert("videos", seed.videos, "id"),
  insert("gallery_albums", seed.albums, "id"),
  insert("gallery_photos", seed.photos, "id"),
  insert("settings", settings, "key"),
].join("\n");

fs.writeFileSync("supabase/seed.sql", sql);
console.log(`seed.sql: ${seed.events.length} events, ${seed.council.length} council, ${seed.photos.length} photos`);
